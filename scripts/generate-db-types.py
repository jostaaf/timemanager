#!/usr/bin/env python3
import re
import sqlite3
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
DATABASE_PATH = ROOT / "database" / "timemanager.db"
OUTPUT_PATH = ROOT / "src" / "server" / "db" / "types.ts"


def type_name(table_name: str) -> str:
    parts = re.findall(r"[A-Za-z0-9]+", table_name)
    name = "".join(part[:1].upper() + part[1:] for part in parts)
    if not name or name[0].isdigit():
        name = f"Table{name}"
    return name


def typescript_type(declared_type: str) -> str:
    normalized = declared_type.upper()
    if "INT" in normalized:
        return "number"
    if any(token in normalized for token in ("CHAR", "CLOB", "TEXT")):
        return "string"
    if any(token in normalized for token in ("REAL", "FLOA", "DOUB")):
        return "number"
    if any(token in normalized for token in ("NUMERIC", "DECIMAL")):
        return "number | string"
    if "BLOB" in normalized or not normalized:
        return "Uint8Array"
    return "number | string"


def main() -> None:
    if not DATABASE_PATH.is_file():
        raise FileNotFoundError(f"SQLite database not found: {DATABASE_PATH}")

    connection = sqlite3.connect(f"file:{DATABASE_PATH}?mode=ro", uri=True)
    try:
        tables = [
            row[0]
            for row in connection.execute(
                """
                SELECT name
                FROM sqlite_master
                WHERE type = 'table' AND name NOT LIKE 'sqlite_%'
                ORDER BY name
                """
            )
        ]
        if not tables:
            raise ValueError(f"No application tables found in {DATABASE_PATH}")

        used_type_names: set[str] = set()
        definitions = [
            "// Generated by scripts/generate-db-types.py; do not edit.",
            "",
        ]
        for table in tables:
            name = type_name(table)
            if name in used_type_names:
                raise ValueError(f"Table names produce a duplicate TypeScript type: {name}")
            used_type_names.add(name)

            columns = connection.execute(
                f'PRAGMA table_info("{table.replace(chr(34), chr(34) * 2)}")'
            ).fetchall()
            if not columns:
                raise ValueError(f"No columns found for table {table!r}")

            definitions.append(f"export interface {name}Table {{")
            for _, column, declared_type, not_null, default, primary_key in columns:
                column_type = typescript_type(declared_type)
                if not not_null and not primary_key:
                    column_type += " | null"
                definitions.append(f"  {column!r}: {column_type};")
            excluded_update_fields = ['"key"', '"version"']
            if any(column[1] == "created_at" for column in columns):
                excluded_update_fields.append('"created_at"')
            excluded_fields = " | ".join(excluded_update_fields)
            defaulted_columns = [column[1] for column in columns if column[4] is not None]
            if defaulted_columns:
                defaulted_fields = " | ".join(
                    f'"{column}"' for column in defaulted_columns
                )
                new_record_type = (
                    f'Omit<{name}Record, {defaulted_fields}> & '
                    f'Partial<Pick<{name}Record, {defaulted_fields}>>'
                )
            else:
                new_record_type = f"{name}Record"
            definitions.extend(
                [
                    "}",
                    f"export type {name}Record = {name}Table;",
                    f"export type New{name}Record = {new_record_type};",
                    f"export type {name}Update = Partial<Omit<{name}Record, {excluded_fields}>>;",
                    "",
                ]
            )

        OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT_PATH.write_text("\n".join(definitions), encoding="utf-8")
    finally:
        connection.close()


if __name__ == "__main__":
    main()
